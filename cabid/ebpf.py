"""eBPF/kernel sensor: real-time process, network, and file events.

CABID's existing collector polls ``/proc`` on an interval, which is cheap and
unprivileged but structurally lossy: a process that starts and exits between two
polls is never seen. A kernel-side sensor closes that gap because the events are
generated by the kernel as they happen.

This module does three things:

1. **Ships the sensor program.** :data:`BPFTRACE_SCRIPT` is a complete bpftrace
   program tracing ``sched_process_exec``, ``sched_process_exit``,
   ``sched_process_fork``, ``sys_enter_connect``, ``sys_exit_openat``, and
   ``sys_enter_unlinkat``, printing one self-describing line per event.
2. **Parses the output.** :func:`parse_line` turns those lines into CABID raw
   events, and :func:`parse_stream` yields them lazily. The parser is strict: an
   unrecognized line is returned as a parse failure with its text, never silently
   guessed into an event.
3. **Degrades honestly.** :func:`capabilities` reports what the current host can
   actually do, and the CLI refuses to pretend. When bpftrace is missing or the
   kernel is locked down, the error names the requirement and does not fall back to
   inventing data.

The output format is versioned and line-oriented on purpose: it survives bpftrace
upgrades better than a struct dump, it can be captured with ``tee`` for later
replay, and everything below can be tested without a kernel.

**Verification status.** This sensor program has not been executed against a live
kernel. The development sandbox has no ``bpftrace``, no kernel BTF, and an
unprivileged user with BPF disabled, so the program was written against the
documented probe and format specifications and the parser was validated against a
corpus of representative output lines. See ``docs/ebpf-sensor.md`` for exactly what
that does and does not establish.
"""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path
from typing import Iterable, Iterator

SENSOR_FORMAT = "cabid-bpf/1"

#: Field separator. A tab is not valid in a kernel path or comm, so it is safe.
SEP = "\t"

#: The bpftrace sensor program.
#:
#: Design notes worth keeping in the file rather than in a commit message:
#: * ``comm`` is capped at 16 bytes by the kernel and can contain spaces, so it is
#:   emitted last on probes where a path precedes it, and paths come from
#:   ``str(args->filename)`` which is NUL-terminated rather than length-prefixed.
#: * Task-level fields use the *current* task on exit probes because ``args`` is
#:   gone after the syscall returns; ``sys_exit_openat`` therefore reports the fd
#:   and the exit status, and the path is taken from the matching enter probe.
#: * Every line starts with the event kind so the parser never guesses.
BPFTRACE_SCRIPT = r"""
/* CABID kernel sensor -- cabid-bpf/1 */
BEGIN {
    printf("cabid-bpf/1\n");
}

tracepoint:sched:sched_process_exec {
    printf("exec\t%llu\t%d\t%d\t%s\t%s\n",
           nsecs / 1000000000, pid, args->old_pid, comm, str(args->filename));
}

tracepoint:sched:sched_process_fork {
    printf("fork\t%llu\t%d\t%d\t%s\n",
           nsecs / 1000000000, args->child_pid, args->parent_pid, comm);
}

tracepoint:sched:sched_process_exit {
    printf("exit\t%llu\t%d\t%d\t%s\n",
           nsecs / 1000000000, pid, args->sig, comm);
}

tracepoint:syscalls:sys_enter_connect {
    printf("connect\t%llu\t%d\t%d\t%s\n",
           nsecs / 1000000000, pid, tid, comm);
}

tracepoint:syscalls:sys_enter_openat {
    printf("open\t%llu\t%d\t%d\t%s\t%s\n",
           nsecs / 1000000000, pid, tid, comm, str(args->filename));
}

tracepoint:syscalls:sys_enter_unlinkat {
    printf("unlink\t%llu\t%d\t%d\t%s\t%s\n",
           nsecs / 1000000000, pid, tid, comm, str(args->filename));
}
"""

#: Probe kinds the parser understands, and the fields each requires.
FIELD_COUNTS = {
    "exec": 5,      # kind, ts, pid, ppid, comm, path  -> 1 + 5
    "fork": 4,      # kind, ts, child, parent, comm
    "exit": 4,      # kind, ts, pid, signal, comm
    "connect": 4,   # kind, ts, pid, tid, comm
    "open": 5,      # kind, ts, pid, tid, comm, path
    "unlink": 5,    # kind, ts, pid, tid, comm, path
}

#: Kernel ``comm`` is 16 bytes including the NUL, so longer values are truncated
#: rather than rejected: the kernel already did the truncation.
MAX_COMM = 16


class SensorError(RuntimeError):
    """Raised when the sensor cannot run or its output cannot be interpreted."""


class ParseError(ValueError):
    """Raised when a sensor line does not match the documented format."""


def capabilities(bpftrace: str = "bpftrace") -> dict:
    """Report whether a kernel sensor can run here, and why not if it cannot.

    Checked in the order that fails first in practice: the userspace tool, then
    privileges, then kernel-side support.
    """
    binary = shutil.which(bpftrace)
    uid = _current_uid()
    btf = Path("/sys/kernel/btf/vmlinux").exists()
    lockdown = _read_first("/sys/kernel/security/lockdown")
    unprivileged = _read_first("/proc/sys/kernel/unprivileged_bpf_disabled")
    reasons: list[str] = []
    if binary is None:
        reasons.append(f"{bpftrace} is not installed")
    if uid != 0:
        reasons.append(f"running as uid {uid}; eBPF tracepoints require root or "
                       "CAP_BPF+CAP_PERFMON")
    if not btf:
        reasons.append("no kernel BTF at /sys/kernel/btf/vmlinux; bpftrace cannot "
                       "resolve kernel types on this build")
    if unprivileged and unprivileged.strip() not in ("0", "2"):
        reasons.append("unprivileged BPF is disabled")
    return {
        "format": SENSOR_FORMAT,
        "bpftrace": binary,
        "available": not reasons,
        "uid": uid,
        "btf_present": btf,
        "lockdown": lockdown,
        "unprivileged_bpf_disabled": unprivileged,
        "reasons": reasons,
        "note": (
            "A sensor that cannot run must say so rather than fall back to polling "
            "silently: the two have different blind spots."),
    }


def _current_uid() -> int:
    try:
        return int(__import__("os").geteuid())
    except (AttributeError, ValueError):  # pragma: no cover - non-POSIX
        return -1


def _read_first(path: str) -> str | None:
    try:
        text = Path(path).read_text(encoding="utf-8", errors="replace").strip()
    except OSError:
        return None
    return text.splitlines()[0] if text else None


def write_script(path: str | Path) -> Path:
    """Materialize the sensor program so it can be reviewed before it is run."""
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(BPFTRACE_SCRIPT.lstrip("\n"), encoding="utf-8")
    return destination


def parse_line(line: str, *, source: str = "ebpf") -> dict:
    """Parse one sensor line into a CABID raw event.

    Raises :class:`ParseError` with the offending text rather than guessing. A
    parser that invents an ``event_type`` for input it does not understand produces
    telemetry that looks complete and is not.
    """
    stripped = line.rstrip("\n")
    if not stripped.strip():
        raise ParseError("empty line")
    if stripped.strip() == SENSOR_FORMAT:
        raise ParseError("format banner, not an event")
    parts = stripped.split(SEP)
    kind = parts[0].strip()
    if kind not in FIELD_COUNTS:
        raise ParseError(f"unknown probe kind {kind!r} in {stripped!r}")
    expected = FIELD_COUNTS[kind]
    if len(parts) != expected + 1:
        raise ParseError(
            f"{kind} expects {expected} field(s), got {len(parts) - 1}: {stripped!r}")
    try:
        timestamp = float(parts[1])
    except ValueError as exc:
        raise ParseError(f"{kind}: timestamp is not a number: {parts[1]!r}") from exc
    if timestamp < 0:
        raise ParseError(f"{kind}: timestamp must be non-negative")

    if kind == "exec":
        pid, ppid = _int(parts[2], kind, "pid"), _int(parts[3], kind, "old_pid")
        comm, path = parts[4], parts[5]
        return _event(timestamp, "process_exec", pid, ppid, comm, path, source)
    if kind == "fork":
        child, parent = _int(parts[2], kind, "child_pid"), _int(parts[3], kind, "parent_pid")
        return _event(timestamp, "process_start", child, parent, parts[4], "", source)
    if kind == "exit":
        pid = _int(parts[2], kind, "pid")
        _int(parts[3], kind, "signal")
        return _event(timestamp, "process_exit", pid, 0, parts[4], "", source)
    if kind == "connect":
        pid = _int(parts[2], kind, "pid")
        _int(parts[3], kind, "tid")
        return _event(timestamp, "network_connect", pid, 0, parts[4], "", source)
    if kind == "open":
        pid = _int(parts[2], kind, "pid")
        _int(parts[3], kind, "tid")
        return _event(timestamp, "file_write", pid, 0, parts[4], parts[5], source)
    # unlink
    pid = _int(parts[2], kind, "pid")
    _int(parts[3], kind, "tid")
    return _event(timestamp, "file_write", pid, 0, parts[4], parts[5], source)


def _int(value: str, kind: str, field: str) -> int:
    try:
        parsed = int(value)
    except ValueError as exc:
        raise ParseError(f"{kind}: {field} is not an integer: {value!r}") from exc
    if parsed < 0:
        raise ParseError(f"{kind}: {field} must be non-negative")
    return parsed


def _event(timestamp: float, event_type: str, pid: int, ppid: int, comm: str,
           target: str, source: str) -> dict:
    if pid <= 0:
        raise ParseError("process id must be positive")
    name = comm.replace("|", "")[:MAX_COMM].strip() or "unknown"
    return {
        "timestamp": timestamp,
        "event_type": event_type,
        "process_id": pid,
        "parent_process_id": max(ppid, 0),
        "process_name": name,
        "executable": target if event_type == "process_exec" else "",
        "target": target,
        "source": source,
    }


def parse_stream(lines: Iterable[str], *, source: str = "ebpf",
                 keep_errors: bool = False) -> Iterator[dict]:
    """Yield parsed events, optionally yield parse failures instead of raising.

    With ``keep_errors`` a failure is yielded as ``{"error": ..., "line": ...}``.
    The CLI uses that mode so one malformed line — a partially written line from a
    killed bpftrace, for instance — does not end a collection run.
    """
    for line in lines:
        try:
            yield parse_line(line, source=source)
        except ParseError as exc:
            if keep_errors:
                yield {"error": str(exc), "line": line.rstrip("\n")[:500]}
                continue
            raise


def run(script_path: str | Path, *, bpftrace: str = "bpftrace",
        timeout: float | None = None) -> list[str]:
    """Run the sensor and return its raw output lines.

    Not used by the test suite: no test in this repository executes bpftrace.
    """
    caps = capabilities(bpftrace)
    if not caps["available"]:
        raise SensorError(
            "kernel sensor cannot run here: " + "; ".join(caps["reasons"]))
    try:
        completed = subprocess.run(
            [str(caps["bpftrace"]), str(script_path)],
            capture_output=True, text=True, timeout=timeout, check=False)
    except subprocess.TimeoutExpired as exc:  # pragma: no cover - needs bpftrace
        raise SensorError(f"sensor timed out after {timeout}s") from exc
    except OSError as exc:  # pragma: no cover - needs bpftrace
        raise SensorError(f"could not start the sensor: {exc}") from exc
    if completed.returncode != 0:
        raise SensorError(
            f"sensor exited with {completed.returncode}: "
            f"{(completed.stderr or '').strip()[:500]}")
    return completed.stdout.splitlines()
